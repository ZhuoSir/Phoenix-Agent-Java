-- V2.1.0_02 知识库向量重建任务（vector-dim-flexibility R-04 / T-10）
-- 目标库：PostgreSQL（phoenix）
-- 幂等：CREATE TABLE / CREATE INDEX 均 IF NOT EXISTS；可重跑
-- 顺序：① 建任务表 ② 索引 ③ 注释
-- 回滚：见 rollback/V2.1.0_02__kb_rebuild_job_ddl_rollback.sql
--
-- 语义注记：
--   · status：PENDING（已创建待跑）/ RUNNING / SUCCEEDED（全部成功且已切换绑定）/
--             PARTIAL（有失败项，未切换绑定，可 retryFailed）/ FAILED（整体异常）
--   · cursor_agent_knowledge_id：断点续跑游标（按条目 id 升序处理，重启后从游标继续，天然幂等）
--   · failed_items：失败清单（jsonb 数组，元素 {id, error}）——失败**不静默跳过**（R-04）
--   · switch_applied：是否已执行"原子切换"（绑定 embedding_model_id/model_space_key 的单条事务更新）
--   · from_model_id：切换前绑定的模型（可追溯）；to_model_id：本次重建目标模型

CREATE TABLE IF NOT EXISTS tbl_data_kb_rebuild_job (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kb_id                       bigint       NOT NULL,
    from_model_id               integer,
    to_model_id                 integer      NOT NULL,
    status                      varchar(24)  NOT NULL DEFAULT 'PENDING',
    total_items                 integer      NOT NULL DEFAULT 0,
    processed_items             integer      NOT NULL DEFAULT 0,
    failed_items                jsonb        NOT NULL DEFAULT '[]'::jsonb,
    cursor_agent_knowledge_id   integer,
    error_msg                   text,
    operator                    varchar(64),
    switch_applied              boolean      NOT NULL DEFAULT false,
    started_time                timestamp(6),
    finished_time               timestamp(6),
    create_time                 timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time                 timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_kbrj_kb ON tbl_data_kb_rebuild_job (kb_id, id DESC);

CREATE INDEX IF NOT EXISTS idx_kbrj_unfinished ON tbl_data_kb_rebuild_job (id) WHERE status IN ('PENDING', 'RUNNING');

COMMENT ON TABLE tbl_data_kb_rebuild_job IS '知识库向量重建任务（R-04）：后台执行、进度可查、失败可重试、断点续跑、完成后原子切换绑定';
